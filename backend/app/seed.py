DAYS = 1460
PASSWORD = "demo123"


def seed_if_empty() -> bool:
    Base.metadata.create_all(bind=engine)
    db = SessionLocal()
    try:
        if db.query(User.id).first() is not None:
            return False
        random.seed(42)
        today = date.today()
        habit_count = 0
        log_rows = []
        for email, name, user_habits in USERS:
            user = User(email=email, name=name, password=PASSWORD)
            db.add(user)
            db.flush()
            for idx, (hname, emoji) in enumerate(user_habits):
                habit = Habit(user_id=user.id, name=hname, emoji=emoji)
                db.add(habit)
                db.flush()
                habit_count += 1
                guaranteed_tail = 0
                if email == "user1@habit.app" and idx < 3:
                    guaranteed_tail = (45, 12, 5)[idx]
                for offset in range(DAYS):
                    d = today - timedelta(days=offset)
                    if offset < guaranteed_tail or random.random() < 0.86:
                        note = None
                        if random.random() < 0.03:
                            note = random.choice(NOTES)
                        log_rows.append({"habit_id": habit.id, "log_date": d, "note": note})
        chunk = 5000
        for i in range(0, len(log_rows), chunk):
            db.execute(insert(HabitLog), log_rows[i : i + chunk])
        db.commit()
        print(f"[seed] {len(USERS)} users, {habit_count} habits, " f"{len(log_rows)} log entries")
        return True
    finally:
        db.close()
